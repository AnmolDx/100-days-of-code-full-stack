//Traffic light system (switch edition)
let color = "green"; //red, yellow, green

switch(color){
    case "red" :
        console.log("stop");
        break;
    case "yellow" :
        console.log("wait");
        break;
    case "green" :
        console.log("go");
        break;
    default:
        console.log("its broken")
}

